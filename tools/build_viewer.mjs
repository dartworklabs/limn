// Builds the viewer's one script, src/limn/viewer/dist/viewer.js, from its ES modules (docs/adr/0042-viewer-es-modules.md,
// docs/adr/0043-viewer-typescript.md, docs/handbook/viewer.md §뷰어 규칙을 바꿀 때).
//
// Rollup follows the static imports of js/main.ts, with types erased and tree-shaking disabled. Every source module
// must be reachable, including modules imported solely for their page listeners or timers.
//
// The result is served as a classic script (GET /viewer.js): it begins with 'use strict' because modules are strict, and
// the server fills its placeholders (__LUCIDE_JSON__, __UI_EN_JSON__, __PDFJS_VERSION__, __KATEX_VERSION__) before
// serving it (limn/viewer/assemble.py). The file is committed: installing Limn needs no Node. CI builds it again with
// --check and fails if the committed bytes differ.
//
// Run: npm ci --ignore-scripts && npm run build        (writes the file)
//      npm run build:check                             (exit 1 when the committed file is not what the modules build)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { rollup } from 'rollup';
import { viewerModules } from './viewer_modules.mjs';
import { stripTypes } from './strip_types.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const VIEWER = join(ROOT, 'src', 'limn', 'viewer');
const OUT = join(VIEWER, 'dist', 'viewer.js');
const BANNER =
  "'use strict';\n" +
  '// Built by tools/build_viewer.mjs from the modules in src/limn/viewer/js (npm run build). Do not edit this file:\n' +
  '// change the modules and build again. CI fails when it is not what they build.';

/** Build one strict classic script from the entry point and reject disconnected source files. */
export async function build(viewer = VIEWER) {
  const modules = new Set(viewerModules(viewer));
  const bundle = await rollup({
    input: join(viewer, 'js/main.ts'),
    treeshake: false,
    plugins: [
      {
        name: 'limn-strip-types',
        transform(code, id) {
          const path = relative(viewer, id).split(sep).join('/');
          if (!modules.has(path) || !path.endsWith('.ts')) this.error(`unexpected viewer module: ${path}`);
          return { code: stripTypes(code, path), map: null };
        },
      },
    ],
    onwarn(warning) {
      throw new Error(`rollup: ${warning.code}: ${warning.message}`);
    },
  });
  try {
    const { output } = await bundle.generate({ format: 'es', banner: BANNER, sourcemap: false });
    if (output.length !== 1) throw new Error(`rollup wrote ${output.length} files, not one`);
    const [chunk] = output;
    const bundled = new Set(chunk.moduleIds);
    const orphans = [...modules].filter((path) => !bundled.has(join(viewer, path)));
    if (orphans.length) throw new Error(`unreachable from js/main.ts: ${orphans.join(', ')}`);
    if (chunk.imports.length || chunk.exports.length) {
      throw new Error('the built script imports or exports something: it would not run as a classic script');
    }
    return chunk.code.endsWith('\n') ? chunk.code : chunk.code + '\n';
  } finally {
    await bundle.close();
  }
}

async function main(argv) {
  const code = await build();
  if (argv.includes('--check')) {
    let committed = '';
    try {
      committed = readFileSync(OUT, 'utf8');
    } catch {
      /* a missing file is stale */
    }
    if (committed !== code) {
      console.error(`${relative(ROOT, OUT)} is not what the modules build: run \`npm run build\` and commit it`);
      return 1;
    }
    console.log(`${relative(ROOT, OUT)} is what the modules build (${code.length} characters)`);
    return 0;
  }
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, code);
  console.log(`wrote ${relative(ROOT, OUT)} (${code.length} characters)`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = await main(process.argv.slice(2));
}
